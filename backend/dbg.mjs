import puppeteer from "puppeteer";
const browser = await puppeteer.launch({ headless: "new", args: ["--no-sandbox","--disable-setuid-sandbox"] });
const page = await browser.newPage();
page.on("pageerror", (e) => console.log("PAGEERROR:\n" + e.stack));
page.on("console", m => console.log("CONSOLE["+m.type()+"]:", m.text()));
const email = `dbg.${Date.now()}@uok.edu.pk`;
await page.goto("http://localhost:4173/register", { waitUntil: "networkidle2", timeout: 40000 });
const inputs = await page.$$("input");
await inputs[0].type("Dr. Debug Tester");
await inputs[1].type(email);
await inputs[2].type("Password123");
await inputs[3].type("Password123");
await page.select("select", "Physics");
await page.click("button[type=submit]");
await new Promise(r=>setTimeout(r,3000));
console.log("AFTER REGISTER path:", await page.evaluate(()=>location.pathname));
console.log("BODY:", (await page.evaluate(()=>document.body.innerText)).slice(0,600));
await page.type("input[type=email]", email);
await page.type("input[type=password]", "Password123");
await page.click("button[type=submit]");
await new Promise(r=>setTimeout(r,4000));
console.log("AFTER LOGIN path:", await page.evaluate(()=>location.pathname));
console.log("localStorage user:", await page.evaluate(()=>localStorage.getItem("uok_user")));
console.log("BODY2:", (await page.evaluate(()=>document.body.innerText)).slice(0,800));
await browser.close();
